"""İnsan yazımı açık kaynak kod derlemi (Python, Kotlin, Java, CSS). Model üretimi yok.

Depo lisansı çağıran tarafından GitHub API'den (license.spdx_id) okunur ve burada yeniden denetlenir: yalnız
derlem-kaynaklar.json → kod.lisans_kabul. Dosya düzeyinde: başlıkta başka lisans (GPL vb.) yazıyorsa, gizli anahtar
izi varsa, üretilmiş/küçültülmüş görünüyorsa atlanır. E-posta adresleri gizlenir. Çıktı: derlem kayıtları (kategori=kod)."""
from __future__ import annotations

import gzip
import hashlib
import json
import re
import tarfile
from collections import Counter
from pathlib import Path

from .shards import ShardWriter

# Dosya başındaki (ilk ~60 satır) başka lisans bildirimleri → dosya atlanır (depo lisansı onu kapsamıyor olabilir)
FOREIGN_LICENSE = re.compile(r"\b(A?GPL|LGPL|GNU (?:Lesser |Affero )?General Public|Mozilla Public License|MPL-2|"
                             r"Eclipse Public License|EPL-|Creative Commons|CC BY-NC|All rights reserved|proprietary|"
                             r"confidential)\b", re.I)
SECRET = re.compile(r"(AKIA[0-9A-Z]{16}|-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY|ghp_[A-Za-z0-9]{30,}|"
                    r"github_pat_[A-Za-z0-9_]{30,}|xox[baprs]-[A-Za-z0-9-]{10,}|sk-[A-Za-z0-9]{32,}|AIza[0-9A-Za-z_-]{35})")
GENERATED = re.compile(r"(auto-?generated|do not edit|generated by|@generated|code generated)", re.I)
EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
TR_CHARS = re.compile(r"[çğıöşüÇĞİÖŞÜ]")


def license_ok(spdx: str | None, accept: list[str]) -> bool:
    return bool(spdx) and spdx.lower() in {a.lower() for a in accept}


def file_reason(path: str, data: bytes, kod: dict) -> str | None:
    """None = alınır; değilse atlama sebebi."""
    lo, hi = kod.get("dosya_bayt", [200, 120000])
    if not (lo <= len(data) <= hi):
        return "boyut"
    p = "/" + path
    if any(s.lower() in p.lower() for s in kod.get("atla_yol", [])):
        return "yol"
    if b"\0" in data:
        return "ikili"
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return "kodlama"
    lines = text.splitlines() or [""]
    if max(len(x) for x in lines) > 1000 or len(text) / len(lines) > 200:
        return "kucultulmus"
    head = "\n".join(lines[:60])
    if GENERATED.search(head):
        return "uretilmis"
    if FOREIGN_LICENSE.search(head):
        return "dosya_lisansi"
    if SECRET.search(text):
        return "gizli_anahtar"
    return None


def norm_code(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\t", "    ")
    text = "\n".join(x.rstrip() for x in text.split("\n"))
    text = re.sub(r"\n{4,}", "\n\n\n", text).strip("\n") + "\n"
    return EMAIL.sub("<GIZLI:EPOSTA>", text)


def iter_tar(tar_path: Path):
    with tarfile.open(tar_path, "r:*") as t:
        for m in t:
            if not m.isfile():
                continue
            # GitHub tarball: <sahip-depo-sha>/yol → kökü at
            rel = m.name.split("/", 1)[1] if "/" in m.name else m.name
            yield rel, m, t


def collect_repo(tar_path: Path, repo: str, spdx: str, kod: dict, out: Path, seen: set[str],
                 ref: str = "HEAD") -> dict:
    """Tek depo tarball'ı → out/kod-<dil>-<depo>-0000.jsonl.gz. seen: içerik özetleri (depolar arası tekilleştirme)."""
    if not license_ok(spdx, kod["lisans_kabul"]):
        return {"depo": repo, "atlandi": f"lisans {spdx}"}
    exts = kod["uzantilar"]
    slug = re.sub(r"[^a-z0-9]+", "-", repo.lower()).strip("-")
    w = ShardWriter(out, f"kod-{slug}")
    drop, langs = Counter(), Counter()
    for rel, m, t in iter_tar(tar_path):
        ext = "." + rel.rsplit(".", 1)[-1] if "." in rel.rsplit("/", 1)[-1] else ""
        lang = exts.get(ext.lower())
        if not lang:
            continue
        if m.size > kod.get("dosya_bayt", [0, 120000])[1]:
            drop["boyut"] += 1
            continue
        data = t.extractfile(m).read()
        why = file_reason(rel, data, kod)
        if why:
            drop[why] += 1
            continue
        text = norm_code(data.decode("utf-8"))
        h = hashlib.sha1(re.sub(r"\s+", "", text).encode()).hexdigest()[:16]
        if h in seen:
            drop["tekrar"] += 1
            continue
        seen.add(h)
        langs[lang] += 1
        w.write({"id": f"kod:{repo}:{rel}", "text": text, "kategori": "kod", "dil": lang, "license": spdx.lower(),
                 "attribution": f"{repo} katkıcıları ({spdx})", "url": f"https://github.com/{repo}/blob/{ref}/{rel}",
                 "kaynak": f"kod-{lang}", "tr_yorum": bool(TR_CHARS.search(text)), "training_allowed": True,
                 "model_uretimi": False})
    w.close()
    return {"depo": repo, "lisans": spdx, "dosya": dict(langs), "karakter": w.chars, "atilan": dict(drop)}


def load_seen(p: Path) -> set[str]:
    if not p.exists():
        return set()
    with gzip.open(p, "rt") as f:
        return {x.strip() for x in f if x.strip()}


def save_seen(p: Path, seen: set[str]) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(p, "wt") as f:
        f.write("\n".join(sorted(seen)))


def main_one(tar: str, repo: str, spdx: str, kod: dict, out: str, seen_file: str, stats_file: str) -> dict:
    seen = load_seen(Path(seen_file))
    st = collect_repo(Path(tar), repo, spdx, kod, Path(out), seen)
    save_seen(Path(seen_file), seen)
    with open(stats_file, "a", encoding="utf-8") as f:
        f.write(json.dumps(st, ensure_ascii=False) + "\n")
    return st
